import assert from "node:assert/strict";
import { mkdtempSync, readFileSync, writeFileSync, mkdirSync, unlinkSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createHash } from "node:crypto";
import { createBudgetGuard, quote, ENDPOINT, LIMIT_MICRO_CNY } from "./budget.mjs";
const parent = mkdtempSync(join(tmpdir(), "ave-paid-budget-"));
const png = Buffer.alloc(24); Buffer.from("89504e470d0a1a0a", "hex").copy(png); png.writeUInt32BE(640, 16); png.writeUInt32BE(360, 20);
const policy = { imageHashes: [createHash("sha256").update(png).digest("hex")], assetHashes: ["a".repeat(64)] };
const planner = text => ({ model: "qwen3.7-max-2026-05-20", messages: [{ role: "user", content: text }], max_tokens: 4096, thinking_budget: 2048, enable_thinking: true });
const vision = { model: "qwen3-vl-plus", messages: [{ role: "user", content: [{ type: "text", text: "synthetic" }, { type: "image_url", image_url: { url: `data:image/png;base64,${png.toString("base64")}` } }] }], max_tokens: 1024, enable_thinking: false };
const init = body => ({ method: "POST", redirect: "error", headers: { authorization: "Bearer offline-fake" }, body: JSON.stringify(body) });
const response = () => new Response(JSON.stringify({ usage: { prompt_tokens: 100, completion_tokens: 200 }, choices: [] }), { status: 200 });
const first = planner("x"), second = planner("y");
const q = quote(first, policy);
assert.equal(q.outputUpper, 4096 + 2048 + 256, "reasoning and tolerance reserved");
assert.equal(q.microCny, q.inputUpper * 12 + q.outputUpper * 36);
assert.equal(quote(vision, policy).inputRate, 1);
const higherVision = structuredClone(vision); higherVision.messages[0].content[0].text = "x".repeat(7700);
assert.equal(quote(higherVision, policy).inputRate, 1.5, "whole request moves to next input tier");
for (const body of [{ ...first, model: "other" }, { ...first, stream: true }, { ...first, tools: [] }, { ...first, n: 2 }, { ...first, max_tokens: 8193 }, { ...vision, enable_thinking: true }, planner("x".repeat(100001)), planner("asset:sha256:" + "b".repeat(64)), planner(JSON.stringify({ profile: { principles: [{ text: "private" }] } }))]) {
  assert.throws(() => quote(body, policy), /REFUSED/);
}
const foreign = structuredClone(vision); foreign.messages[0].content[1].image_url.url = "https://example.org/private.png";
assert.throws(() => quote(foreign, policy), /REFUSED/);
let sent = 0;
const directory = join(parent, "concurrent");
const guard = createBudgetGuard({ directory, policy, limitMicroCny: q.microCny, fetchImpl: async (url, options) => {
  assert.equal(url, ENDPOINT); assert.equal(options.headers.authorization, "Bearer offline-fake");
  assert.match(readFileSync(join(directory, "ledger.jsonl"), "utf8"), /"kind":"reserved"/, "reservation is durable before original fetch");
  sent++; return response();
} });
assert.throws(() => createBudgetGuard({ directory, policy, fetchImpl: async () => response() }), /EEXIST/, "second process/owner cannot race ledger");
const attempts = await Promise.allSettled([guard.fetch(ENDPOINT, init(first)), guard.fetch(ENDPOINT, init(second))]);
assert.equal(attempts.filter(x => x.status === "fulfilled").length, 1); assert.equal(sent, 1);
assert.equal(guard.snapshot().reservedMicroCny, q.microCny, "successful response never refunds reservation");
await assert.rejects(guard.fetch(ENDPOINT, init(first)), /blind replay/);
guard.close();
const restarted = createBudgetGuard({ directory, policy, limitMicroCny: q.microCny, fetchImpl: async () => { sent++; return response(); } });
assert.equal(restarted.snapshot().reservedMicroCny, q.microCny);
await assert.rejects(restarted.fetch(ENDPOINT, init(second)), /cumulative/); assert.equal(sent, 1);
restarted.close();
const uncertainDir = join(parent, "uncertain");
const uncertain = createBudgetGuard({ directory: uncertainDir, policy, fetchImpl: async () => { throw new Error("offline socket uncertainty"); } });
await assert.rejects(uncertain.fetch(ENDPOINT, init(first)), /socket uncertainty/);
assert.equal(uncertain.snapshot().reservedMicroCny, q.microCny);
await assert.rejects(uncertain.fetch(ENDPOINT, init(first)), /blind replay/);
// An explicitly different later request still consumes cumulative reservation.
await assert.rejects(uncertain.fetch(ENDPOINT, init(second)), /socket uncertainty/);
assert.equal(uncertain.snapshot().reservedMicroCny, q.microCny * 2);
uncertain.close();
const unknown = createBudgetGuard({ directory: join(parent, "unknown-usage"), policy, fetchImpl: async () => new Response("bad json", { status: 503 }) });
await unknown.fetch(ENDPOINT, init(first));
assert.equal(unknown.snapshot().reservedMicroCny, q.microCny); unknown.close();
const failedDiskDir = join(parent, "failed-ledger");
const failedDisk = createBudgetGuard({ directory: failedDiskDir, policy, fetchImpl: async () => { throw new Error("must not send"); } });
unlinkSync(join(failedDiskDir, "ledger.jsonl"));
mkdirSync(join(failedDiskDir, "ledger.jsonl"));
await assert.rejects(failedDisk.fetch(ENDPOINT, init(first)));
assert.equal(failedDisk.snapshot().frozen, true); failedDisk.close();
writeFileSync(join(directory, "ledger.jsonl"), "corrupt\n");
