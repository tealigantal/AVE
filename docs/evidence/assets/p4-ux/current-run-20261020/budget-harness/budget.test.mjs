const publicUrl = "https://opengameart.org/sites/default/files/acceptance-offline.mp3";
let publicGets = 0;
const publicAudio = createBudgetGuard({directory:join(parent,"public-audio"),policy:{...policy,audioDownloads:[{kind:"direct",url:publicUrl}]},fetchImpl:async()=>{publicGets++;return response();}});
