import assert from "node:assert/strict";
import { readdir, readFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "../..");
const rendererRoot = resolve(root, "apps/desktop/src/renderer");
const requiredDirectories = ["app", "workbench", "features", "api", "state", "components", "styles"];
for (const directory of requiredDirectories) assert.equal((await readdir(resolve(rendererRoot, directory))).length > 0, true, `renderer/${directory} is empty`);
const html = await readFile(resolve(rendererRoot, "index.html"), "utf8");
assert.match(html, /src="\/app\/main\.js"/);
assert.match(html, /href="\/styles\/workbench\.css"/);
const sourceFiles = [];
for (const directory of requiredDirectories) for (const entry of await readdir(resolve(rendererRoot, directory))) if (/\.(?:js|ts|tsx)$/.test(entry)) sourceFiles.push(await readFile(resolve(rendererRoot, directory, entry), "utf8"));
const source = sourceFiles.join("\n");
assert.doesNotMatch(source, /project\.sqlite|node:fs|node:child_process|ffmpeg|ffprobe|better-sqlite|from\s+["']electron["']/i);
assert.match(source, /projectApi/);
assert.match(source, /command\(/);
assert.match(source, /query\(/);
assert.doesNotMatch(source, /localStorage|indexedDB|timeline\s*=\s*\{/i);
const stage2WorkspaceSource = await readFile(resolve(rendererRoot, "features/stage2-workspace.js"), "utf8");
const workbenchSource = await readFile(resolve(rendererRoot, "workbench/workbench.js"), "utf8");
assert.match(stage2WorkspaceSource, /feedback-target/);
assert.match(stage2WorkspaceSource, /请选择要修改的镜头/);
assert.match(stage2WorkspaceSource, /actions\.createFeedback\(input\.value, seconds\.value, targetSelect\.value\)/);
assert.doesNotMatch(workbenchSource, /editable_targets\?\.\[0\]/, "feedback must not silently bind the first editable clip");
assert.match(stage2WorkspaceSource, /editable_targets\?\.find\(\(item\) => feedbackTargetKey\(item\) === targetKey\)/);
assert.match(workbenchSource, /prepareStage2FeedbackRequest\(state\.stage2Workspace, feedbackText, trimSeconds, targetKey, crypto\.randomUUID\(\)\)/);
assert.match(stage2WorkspaceSource, /建立 Creative Contract/);
assert.match(stage2WorkspaceSource, /AVE 不会代填或伪造隐私、权利策略摘要/);
assert.match(stage2WorkspaceSource, /stage2CandidateSelectionState\(workspace\?\.directions/);
assert.match(stage2WorkspaceSource, /stage2CandidateSelectionState\(workspace\?\.stories/);
assert.match(stage2WorkspaceSource, /stage2GenerationControlState\(workspace\)\.canGenerateDirections/);
assert.match(stage2WorkspaceSource, /stage2GenerationControlState\(workspace\)\.canGenerateStories/);
assert.match(stage2WorkspaceSource, /card\.disabled = !selectable/);
assert.match(workbenchSource, /stage2CandidateSelectionState\(stage2\.data\.directions/, "workspace refresh must clear retained selections that are no longer current candidates");
assert.match(workbenchSource, /stage2CandidateSelectionState\(stage2\.data\.stories/, "workspace refresh must clear retained Story selections that are no longer current candidates");
assert.match(workbenchSource, /project\.stage2\.contract\.create/);
assert.match(workbenchSource, /project\.stage2\.execution\.render/);
assert.match(workbenchSource, /track_id: "video-reference"/);
assert.match(workbenchSource, /project\.stage2\.preview\.current/);
for (const removed of ["project.preview.latest", "project.render", "project.review.list", "project.delivery.list", "project.export.list", "project.model.runs", "project.qc.issues", "project.render.latest", "project.render.results", "legacy-workbench"]) assert.doesNotMatch(workbenchSource, new RegExp(removed.replaceAll(".", "\\.")), `${removed} must not remain in the canonical Renderer path`);
for (const removedState of ["storyPlans", "reviewArtifacts", "deliveryRecords", "exports", "modelRuns", "qcIssues", "storyCandidate", "renderLatest", "renderResults"]) assert.doesNotMatch(source, new RegExp(`\\b${removedState}\\b`), `${removedState} compatibility state must be removed`);
assert.doesNotMatch(workbenchSource, /executionBinding|source_identity_digest|preview_plan_id|master_plan_id/, "Renderer must never construct Stage 2 render authority");
assert.doesNotMatch(workbenchSource, /editorialPanel|project\.story\.(?:list|propose|approve)|project\.assembly\.|project\.review\.diagnosis/, "Workbench must not retain the old editorial route");
console.log("renderer workbench boundary check passed");
