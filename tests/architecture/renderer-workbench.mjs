import assert from "node:assert/strict";
import { readdir, readFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "../..");
const rendererRoot = resolve(root, "apps/desktop/src/renderer");
const requiredDirectories = ["app", "workbench", "features", "api", "state", "components", "styles"];
for (const directory of requiredDirectories) assert.equal((await readdir(resolve(rendererRoot, directory))).length > 0, true, `renderer/${directory} is empty`);
const html = await readFile(resolve(rendererRoot, "index.html"), "utf8");
assert.match(html, /src="\/app\/main\.js"/);
assert.match(html, /href="\/styles\/workbench\.css"/);
const sourceFiles = [];
for (const directory of requiredDirectories) for (const entry of await readdir(resolve(rendererRoot, directory))) if (/\.(?:js|ts|tsx)$/.test(entry)) sourceFiles.push(await readFile(resolve(rendererRoot, directory, entry), "utf8"));
const source = sourceFiles.join("\n");
assert.doesNotMatch(source, /project\.sqlite|node:fs|node:child_process|ffmpeg|ffprobe|better-sqlite|from\s+["']electron["']/i);
assert.match(source, /projectApi/);
assert.match(source, /command\(/);
assert.match(source, /query\(/);
assert.doesNotMatch(source, /localStorage|indexedDB|timeline\s*=\s*\{/i);
const creationSource = await readFile(resolve(rendererRoot, "features/creation-workspace.js"), "utf8");
const workbenchSource = await readFile(resolve(rendererRoot, "workbench/workbench.js"), "utf8");
const playerSource = await readFile(resolve(rendererRoot, "features/player-panel.js"), "utf8");
for (const route of ["begin", "revise", "cancel", "material.prepare", "observe", "generate", "manual", "render", "select", "learn", "workspace", "timeline", "preview"]) assert.ok(workbenchSource.includes(`project.creation.${route}`), `missing current route ${route}`);
for (const route of ["configure", "forget"]) assert.ok(workbenchSource.includes(`project.profile.${route}`));
for (const input of ["original_text", "asset_ids", "allowed_data", "provider", "model", "protected_refs", "expires_at", "preserve_refs", "correction_ids", "exceptions"]) assert.ok(creationSource.includes(input), `explicit user scope missing: ${input}`);
assert.doesNotMatch(creationSource, /max_cost|max_calls|max_input_bytes|input_token_counter|tariff/, "retired product quota interface must not remain in Renderer");
assert.match(creationSource, /JSON\.stringify\(\[track\.track_id,clip\.clip_id\]\)/);
assert.match(creationSource, /authorizationAssets\(state\.media\)/);
assert.match(workbenchSource, /manualCommands\(state\.timeline, values, operation_id\)/);
assert.doesNotMatch(workbenchSource, /editable_targets\?\.\[0\]|video-reference|project\.stage2\./);
assert.match(workbenchSource, /startedSelection === selectionEpoch/);
assert.match(workbenchSource, /scopeEpoch !== epoch/);
assert.match(workbenchSource, /output_hash !== binding\.output_hash/);
assert.match(workbenchSource, /pointer: "adopted"/); assert.match(workbenchSource, /pointer: "viewed"/);
assert.match(playerSource, /addEventListener\("playing",onPlaying\)/);
assert.match(playerSource, /loaded !== state\.previewUrl/);
assert.doesNotMatch(playerSource, /innerHTML.*video|replaceChildren/);
assert.match(creationSource, /activeScope === key/);
assert.match(workbenchSource, /CREATION_RENDER_ATTEMPT_FAILED/); assert.match(workbenchSource, /retryRender:/);
for (const removed of ["project.preview.latest", "project.render", "project.review.list", "project.delivery.list", "project.export.list", "project.model.runs", "project.qc.issues", "project.render.latest", "project.render.results", "legacy-workbench"]) assert.doesNotMatch(workbenchSource, new RegExp(removed.replaceAll(".", "\\.")), `${removed} must not remain in the canonical Renderer path`);
for (const removedState of ["storyPlans", "reviewArtifacts", "deliveryRecords", "exports", "modelRuns", "qcIssues", "storyCandidate", "renderLatest", "renderResults"]) assert.doesNotMatch(source, new RegExp(`\\b${removedState}\\b`), `${removedState} compatibility state must be removed`);
assert.doesNotMatch(workbenchSource, /executionBinding|source_identity_digest|preview_plan_id|master_plan_id/, "Renderer must never construct render authority");
assert.doesNotMatch(workbenchSource, /editorialPanel|project\.story\.(?:list|propose|approve)|project\.assembly\.|project\.review\.diagnosis/, "Workbench must not retain the old editorial route");
console.log("renderer workbench boundary check passed");
